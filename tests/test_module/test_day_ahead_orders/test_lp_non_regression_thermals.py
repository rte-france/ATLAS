# Timestamp pattern at the end of legacy variable names: YYYY_MM_DD_HH_MM_SS_TZ_TZ
_TIMESTAMP_RE = re.compile(r"(\d{4}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2})$")

# ── Pattern A: {ROLE}_equip_{unit}_at_{time} ──────────────────────────────────
# Maps legacy role prefix → new role prefix.
# "power" and "down_to_stop" are handled separately.
_EQUIP_PREFIX_MAP: dict[str, str] = {
    "OFF": "off",
    "ON_UP": "on_up",
    "ON_DOWN": "on_down",
    "ON_FLAT": "on_flat",
    "START": "on_start",
    "STOP": "stop",
    "turned_on": "t_on",
    "turned_off": "t_off",
    "reservesUp": "reserves_up",
    "reservesDown": "reserves_down",
    "automatedReservesUp": "automated_reserves_up",
    "automatedReservesDown": "automated_reserves_down",
    "relaxedReserves": "relaxed_reserves",
    "unprovidedReservesUp": "unprovided_reserves_up",
    "unprovidedReservesDown": "unprovided_reserves_down",
    "contractedDifferenceUp": "contracted_difference_up",
    "contractedDifferenceDown": "contracted_difference_down",
    "automatedContractedDifferenceUp": "automated_contracted_difference_up",
    "automatedContractedDifferenceDown": "automated_contracted_difference_down",
}

# ── Pattern B: {role}_at_{time}  (no unit embedded, time before unit) ─────────
# These gradient/state variables did not embed the unit name in the legacy code.
# The new ThermalDispatch appends the unit: {new_role}_{time}_{unit}.
_AT_PREFIX_MAP: dict[str, str] = {
    "UP_grad": "up_grad",
    "DOWN_grad": "down_grad",
    "aux_up_grad": "aux_up_grad",
    "aux_down_grad": "aux_down_grad",
    "entered_up": "entered_up",
    "entered_down": "entered_down",
    "stable": "stable",
    "flat_down_stop": "flat_down_stop",
    # DD variants: the legacy used either "DD_at" or "DD" depending on combination
    "DD_at": "dd_grad",
    "DD": "dd_grad",
}

# Gradient variable prefixes whose bounds differ between legacy and current:
# legacy used global max_power over the horizon; ThermalDispatch uses per-timestep max_power.
# The new bounds are strictly tighter (valid relaxation) — excluded from bounds comparison.
_GRADIENT_VAR_PREFIXES: frozenset[str] = frozenset(
    {"up_grad", "down_grad", "aux_up_grad", "aux_down_grad", "dd_grad", "down_to_stop_grad"}
)


def _normalize_legacy_name(name: str, unit: str) -> str:
    """
    Translate a single legacy DA variable name to its current ThermalDispatch equivalent.

    Three naming patterns exist in the legacy LP files:

    - Pattern A: ``{ROLE}_equip_{unit}_at_{time}`` — standard DA variables
    - Pattern C: ``{role}_at_{time}_equip_{unit}`` — gradient/state variables (time first)
    - Pattern C': ``{role}_{time}_equip_{unit}``  — DD variant without ``_at_``

    :param name: Legacy variable name.
    :param unit: The thermal unit name (used to validate the unit embedded in the name).
    :return: Normalized name, or *name* unchanged if no mapping is found.
    """
    if "_equip_" not in name:
        return name

    role, rest = name.split("_equip_", maxsplit=1)
    at_idx = rest.rfind("_at_")

    if at_idx != -1:
        # ── Pattern A: {ROLE}_equip_{unit}_at_{time} ──────────────────────────
        eq_unit = rest[:at_idx]
        timestamp = rest[at_idx + 4:]
        if not _TIMESTAMP_RE.match(timestamp):
            return name

        if role == "power":
            return f"{eq_unit}_power_level_{timestamp}"
        if role == "down_to_stop":
            return f"down_to_stop_grad_{timestamp}_{eq_unit}"

        new_role = _EQUIP_PREFIX_MAP.get(role)
        if new_role is None:
            return name
        return f"{new_role}_{eq_unit}_{timestamp}"

    # ── Patterns C / C': gradient vars — time is embedded in "role" part ──────
    # rest is just the unit name here (no "_at_" in it).
    eq_unit = rest  # unit embedded after _equip_

    # Pattern C: {role}_at_{time}_equip_{unit}
    role_at_idx = role.rfind("_at_")
    if role_at_idx != -1:
        role_candidate = role[:role_at_idx]
        timestamp = role[role_at_idx + 4:]
        if _TIMESTAMP_RE.match(timestamp):
            new_role = _AT_PREFIX_MAP.get(role_candidate)
            if new_role is not None:
                return f"{new_role}_{timestamp}_{eq_unit}"

    # Pattern C': {role}_{time}_equip_{unit}  (e.g. DD_{time}_equip_{unit})
    parts = role.split("_", maxsplit=1)
    if len(parts) == 2 and parts[0] in _AT_PREFIX_MAP and _TIMESTAMP_RE.match(parts[1]):
        return f"{_AT_PREFIX_MAP[parts[0]]}_{parts[1]}_{eq_unit}"

    return name


def _extract_unit_name(lp_data: dict) -> str:
    """
    Derive the thermal unit name from an LP data dict.

    The unit name is embedded in variables such as ``off_{unit}_{timestamp}``.
    We locate the first ``off_`` variable and strip the well-known timestamp suffix.
    Falls back to an empty string if the pattern is not found.
    """
    timestamp_re = re.compile(r"_\d{4}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}_\d{2}$")
    for var_name in lp_data.get("variables", {}):
        if var_name.startswith("off_"):
            return timestamp_re.sub("", var_name[len("off_"):])
    return ""


def _constraint_signature(constraint: dict, unit: str) -> tuple:
    """
    Build a hashable, name-agnostic signature for a single constraint.

    The signature is ``(sorted_var_rows, lb, ub)`` where each var row is
    ``(normalized_variable_name, coefficient)``.  Sorting makes it
    order-independent while keeping variable names for debuggability.
    """
    vars_items = tuple(
        sorted(
            (_normalize_legacy_name(var, unit), round(coeff, 8))
            for var, coeff in constraint.get("vars", {}).items()
        )
    )
    lb = constraint.get("lb")
    ub = constraint.get("ub")
    return (vars_items, lb, ub)


def _constraint_signatures(lp_data: dict, unit: str) -> Counter:
    return Counter(
        sig
        for c in lp_data["constraints"].values()
        if (sig := _constraint_signature(c, unit))[0]  # skip empty rows (LP parser artifacts)
    )


def _normalize_lp_named(lp_data: dict, unit: str) -> dict:
    """Return a copy with variable names translated (objectives + variable bounds only)."""

    def rename(mapping: dict) -> dict:
        return {_normalize_legacy_name(k, unit): v for k, v in mapping.items()}

    return {
        "objectives": rename(lp_data.get("objectives", {})),
        "variables": rename(lp_data.get("variables", {})),
        "constraints": lp_data.get("constraints", {}),
        "binaries": [_normalize_legacy_name(b, unit) for b in lp_data.get("binaries", [])],
    }


