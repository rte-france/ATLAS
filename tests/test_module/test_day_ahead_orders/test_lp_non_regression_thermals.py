def _generate_current_lp(combination_dir: Path, params: dict) -> dict:
    with tempfile.TemporaryDirectory() as tmpdir:
        params = params.copy()
        params["output"] = {"output_dir": tmpdir}
        DayAheadOrdersModule().run(AtlasDataset.from_directory(combination_dir), params)
        lp_files = list((Path(tmpdir) / "lp_export").glob("*.lp"))
        assert lp_files, f"No LP generated for {combination_dir.name}"
        return SolverHelper.read_lp_ortools(str(lp_files[0]))


class TestThermalNonRegression:
    """
    Validates that the ThermalDispatch refactoring did not change the
    mathematical content of the LP — only the naming conventions.
    """

    def test_variables_and_objective_match(self, thermal_combination, base_parameters_dict):
        """Variable bounds and objective coefficients are identical after name normalization.

        Gradient variables (up_grad, down_grad, aux_up_grad, aux_down_grad, dd_grad,
        down_to_stop_grad) are excluded from the bounds comparison: the legacy code
        computed bounds from the global maximum power over the horizon while ThermalDispatch
        uses per-timestep maximum_power.  The new bounds are strictly tighter, which is a
        valid relaxation that does not change the optimal solution.
        """
        num, combination_dir, legacy_lp = thermal_combination

        current = _generate_current_lp(combination_dir, base_parameters_dict)
        legacy_raw = SolverHelper.read_lp_ortools(str(legacy_lp))
        unit = _extract_unit_name(current)
        legacy = _normalize_lp_named(legacy_raw, unit)

        def _drop_gradient_vars(lp: dict) -> dict:
            return {
                **lp,
                "variables": {
                    k: v
                    for k, v in lp["variables"].items()
                    if not any(k.startswith(pfx + "_") for pfx in _GRADIENT_VAR_PREFIXES)
                },
            }

        legacy_cmp = _drop_gradient_vars(legacy)
        current_cmp = _drop_gradient_vars(current)

        with tempfile.TemporaryDirectory() as compare_dir:
            result = SolverHelper.compare_lp_problems(
                legacy_cmp,
                current_cmp,
                output_dir=compare_dir,
                pb1_name="Legacy (normalized)",
                pb2_name="Current",
                tolerance=1,
                normalize_names=False,
                keep_identical=False,
            )

        for category in ("objectives", "variables"):
            assert result[category]["identical_pct"] == 100.0, (
                f"[combination-{num}] {category}: {result[category]['identical_pct']:.1f}% identical — "
                f"only_legacy={result[category]['only_legacy']}, "
                f"only_current={result[category]['only_atlas']}, "
                f"modified={result[category]['modified']}"
            )

    def test_constraints_structurally_match(self, thermal_combination, base_parameters_dict):
        """
        Constraints are identical as mathematical rows (name-agnostic comparison).

        Each constraint is fingerprinted as (sorted[(normalized_var, coeff)...], lb, ub).
        If this test fails, the diff shows which constraint rows are missing or extra —
        with all variable names visible so you can trace back to the code.
        """
        num, combination_dir, legacy_lp = thermal_combination

        current = _generate_current_lp(combination_dir, base_parameters_dict)
        legacy_raw = SolverHelper.read_lp_ortools(str(legacy_lp))
        unit = _extract_unit_name(current)

        legacy_sigs = _constraint_signatures(legacy_raw, unit)
        current_sigs = _constraint_signatures(current, unit)

        only_legacy = legacy_sigs - current_sigs
        only_current = current_sigs - legacy_sigs

        def _fmt(counter: Counter, limit: int = 5) -> str:
            lines = []
            for sig, count in list(counter.items())[:limit]:
                vars_part = ", ".join(f"{v}×{c}" for v, c in sig[0])
                lines.append(f"  (count={count}) [{vars_part}] lb={sig[1]} ub={sig[2]}")
            if len(counter) > limit:
                lines.append(f"  ... and {len(counter) - limit} more")
            return "\n".join(lines)

        assert not only_legacy and not only_current, (
            f"[combination-{num}] Constraint mismatch:\n"
            f"Only in legacy ({sum(only_legacy.values())} rows):\n{_fmt(only_legacy)}\n"
            f"Only in current ({sum(only_current.values())} rows):\n{_fmt(only_current)}"
        )
